import type { MicromarkToken, Rule, RuleParams } from "markdownlint";

const terminatorPattern = /[.!?]/gu;
const whitespacePattern = /\s/u;
const semicolonPattern = /(?<semicolon>[;；;])/gu;
const abbreviationTailPattern =
  /(?:\b(?:e\.g|i\.e|etc|vs|cf|approx|Inc|Ltd|Co|Corp|Jr|Sr|Dr|Mr|Mrs|Ms|St|Fig|No|ed|al)|(?:[A-Z]\.)+[A-Z])$/u;
const initialNameContextPattern =
  /(?:^|\b(?:Ask|Contact|by|from|with|(?:Dr|Mr|Mrs|Ms)\.?)\s+)[A-Z]$/u;
const surnameStartPattern = /^[A-Z][a-z]+\b/u;
const entityTailPattern = /&(?:#\d+|#[\da-fA-F]+|[a-zA-Z][\d]{2,31})$/u;
const conjunctiveAdverbPattern =
  /^(?:however|therefore|thus|hence|instead|otherwise|besides|accordingly|consequently|furthermore|moreover|nevertheless|nonetheless|similarly|likewise|meanwhile|subsequently|additionally|alternatively)\b/iu;
const imperativeTailVerbs =
  "retry|rerun|resume|restart|return|repeat|replace|remove|restore|reset|rebuild|record|report|repoint|reject|require|request|reuse|run|write|use|set|send|keep|leave|copy|check|confirm|continue|verify|wait|add|apply|change|delete|drop|edit|fix|load|open|pin|scan|show|skip|test|treat|validate|view";
const finiteTailVerbs =
  "is|are|was|were|be|been|being|has|have|had|does|do|did|will|would|can|could|shall|should|may|might|must|stays?|remains?|starts?|ends?|fails?|passes?|follows?|returns?|owns?|moves?|loses?|gains?|keeps?|uses?|covers?|certif(?:ies|y)|validates?|loads?|ships?|runs?|exists?|" +
  `(?:${imperativeTailVerbs
    .split("|")
    .filter(
      (stem) => stem.endsWith("e") && stem !== "leave" && stem !== "write"
    )
    .map((stem) => `${stem}d`)
    .join(
      "|"
    )})(?=\\s+the\\s+(?!(?:most|least|worst|[\\p{L}\\p{N}\\p{M}_'’-]*est)(?:[.!?;；]|$))[\\p{L}\\p{N}][\\p{L}\\p{N}\\p{M}_'’-]*(?:[.!?;；]|$))`;
const subjectLeads =
  "this|that|these|those|it|they|we|you|he|she|who|which|another|each|every|some|all|both|one|two|three|the|a|an";
const clauseStartPattern = new RegExp(
  `^(?:(?:${imperativeTailVerbs})\\b|(?!${subjectLeads}\\b)[a-z\\d][\\w'’-]*\\s+(?:${finiteTailVerbs})\\b|(?:this|that|these|those|it|they|we|you|he|she|who|which)\\s+(?:${finiteTailVerbs})\\b|(?:${subjectLeads})\\b(?:\\s+[a-z][\\w'’-]*){1,2}\\s+(?:${finiteTailVerbs})\\b)`,
  "iu"
);
const imperativeContinuationPattern = new RegExp(
  `^(?:${imperativeTailVerbs}|preserve|do)\\b`,
  "iu"
);
const sentenceStartPattern = /^[A-Z0-9"'“([「『*]/u;
const wordBeforePattern = /[\w"”’\])]/u;
const wordAfterPattern = /[\w"'“([/]/u;
const closingQuotePattern = /^["'”’]+/u;
const protectedTextPattern =
  /"(?:\\[\s\S]|[^"\\])*"|“(?:\\[\s\S]|[^”\\])*”|(?<!\w)'(?:\\[\s\S]|(?<=\w)'(?=\w)|[^'\\])*'(?!\w)|‘(?:\\[\s\S]|(?<=\w)’(?=\w)|[^’\\])*’/gu;
const alertPattern =
  /^ {0,3}(?:>[ \t]*)+\[!(?:NOTE|TIP|IMPORTANT|WARNING|CAUTION)\][ \t]*(?:\r\n|\r|\n|$)/iu;
const opaqueInlineTypes = new Set([
  "link",
  "image",
  "codeText",
  "literalAutolink",
  "autolink"
]);
const licenseNamePattern =
  /(?:^|[/\\])(?:licen[cs]e|copying)(?:[.-][^/\\]*)?$/iu;
const generatedMarkerPattern =
  /^\s*(?:<!--\s*(?:generated(?:\s+file)?|automatically generated|auto-generated)\b|(?:generated|autogenerated):\s*true\s*$)/iu;
const skippedContainerTypes = new Set([
  "htmlFlow",
  "codeFenced",
  "codeIndented",
  "htmlFlowData"
]);

interface Segment {
  startColumn: number;
  text: string;
}

interface Finding {
  column: number;
  length: number;
}

/**
 * Walks token children depth-first and collects prose blocks outside excluded containers.
 */
const proseBlocks = (tokens: readonly MicromarkToken[]): MicromarkToken[] => {
  const blocks: MicromarkToken[] = [];
  const visit = (token: MicromarkToken) => {
    if (token.type === "paragraph") {
      blocks.push(token);
    } else if (
      !skippedContainerTypes.has(token.type) &&
      (token.type !== "blockQuote" || alertPattern.test(token.text))
    ) {
      for (const child of token.children) {
        visit(child);
      }
    }
  };
  for (const token of tokens) {
    visit(token);
  }
  return blocks;
};

/**
 * Collects prose text segments of one paragraph grouped by physical line.
 */
const segmentsByLine = (paragraph: MicromarkToken): Map<number, Segment[]> => {
  const byLine = new Map<number, Segment[]>();
  const visit = (token: MicromarkToken) => {
    const opaque = opaqueInlineTypes.has(token.type);
    if ((token.type === "data" || opaque) && token.text.trim() !== "") {
      const prose = opaque
        ? token.text.replaceAll(/[^\r\n]/gu, (character) =>
            "_".repeat(character.length)
          )
        : token.text;
      const lines = prose.split(/\r\n|\r|\n/u);
      for (const [index, text] of lines.entries()) {
        if (text.trim() !== "") {
          const lineNumber = token.startLine + index;
          const startColumn = index === 0 ? token.startColumn : 1;
          const bucket = byLine.get(lineNumber) ?? [];
          bucket.push({ startColumn, text });
          byLine.set(lineNumber, bucket);
        }
      }
    }
    if (!opaque) {
      for (const child of token.children) {
        visit(child);
      }
    }
  };
  visit(paragraph);
  return byLine;
};

/**
 * Rebuilds one physical line from prose segments, keeping UTF-16 source columns.
 */
const rebuildLine = (segments: readonly Segment[]): string => {
  const units: (string | undefined)[] = [];
  for (const segment of segments) {
    const offset = segment.startColumn - 1;
    for (let index = 0; index < segment.text.length; index += 1) {
      units[offset + index] = segment.text[index];
    }
  }
  let line = "";
  for (const unit of units) {
    line += unit ?? " ";
  }
  return line;
};

/**
 * Masks literal quotations while preserving source coordinates.
 * A quotation's final terminator can still separate surrounding prose sentences.
 */
const protectText = (text: string): string =>
  text.replaceAll(protectedTextPattern, (match) => {
    const ending = /(?<ending>[.!?]["'”’])$/u.exec(match)?.groups?.ending ?? "";
    const masked = match.replaceAll(/[^\r\n]/gu, (character) =>
      " ".repeat(character.length)
    );
    return ending === ""
      ? `${masked.slice(0, -1)}_`
      : `${masked.slice(0, -ending.length - 1)}_${ending}`;
  });

/**
 * Identifies license files and generated documents before inspecting their prose.
 */
const protectedDocument = (params: RuleParams): boolean =>
  licenseNamePattern.test(params.name) ||
  params.frontMatterLines.some((line) => generatedMarkerPattern.test(line)) ||
  (params.parsers.micromark?.tokens ?? []).some(
    (token) =>
      token.type === "htmlFlow" &&
      token.startLine <= 5 &&
      generatedMarkerPattern.test(token.text)
  );

/**
 * Finds clear wrapped prose or unterminated instructions on adjacent source lines.
 */
const continuation = (
  previous: string | undefined,
  line: string
): Finding | undefined => {
  const start = line.trimStart();
  if (
    previous !== undefined &&
    previous !== "" &&
    /[a-z0-9]$/iu.test(previous.trimEnd()) &&
    (/^[a-z]/u.test(start) || imperativeContinuationPattern.test(start))
  ) {
    return { column: line.length - start.length + 1, length: 1 };
  }
  return undefined;
};

/**
 * Finds a terminator that ends one independent sentence and starts another.
 */
const joinedSentence = (line: string): Finding | undefined => {
  for (const match of line.matchAll(terminatorPattern)) {
    const index = match.index ?? 0;
    const after = line.slice(index + 1).replace(closingQuotePattern, "");
    const [next] = after;
    const before = line.slice(0, index);
    const remainder = after.trim();
    if (
      (next === undefined || whitespacePattern.test(next)) &&
      wordBeforePattern.test(line[index - 1] ?? "") &&
      (!abbreviationTailPattern.test(before) ||
        (/\b(?:etc|Inc|Ltd|Co|Corp)$/u.test(before) &&
          clauseStartPattern.test(remainder))) &&
      !(
        initialNameContextPattern.test(before.trimStart()) &&
        surnameStartPattern.test(remainder) &&
        !imperativeContinuationPattern.test(remainder)
      ) &&
      remainder !== "" &&
      sentenceStartPattern.test(remainder)
    ) {
      return { column: index + 1, length: 1 };
    }
  }
  return undefined;
};

/**
 * Finds a semicolon used to join independent prose on one line.
 */
const joinedSemicolon = (line: string): Finding | undefined => {
  for (const match of line.matchAll(semicolonPattern)) {
    const index = match.index ?? 0;
    const before = line.slice(0, index);
    const tail = line.slice(index + 1).trimStart();
    const previous = before.trimEnd().at(-1);
    const next = tail.at(0);
    if (
      !entityTailPattern.test(before) &&
      previous !== undefined &&
      next !== undefined &&
      wordBeforePattern.test(previous) &&
      wordAfterPattern.test(next) &&
      !(
        /(?:^|[.!?]\s+)[^.!?]*:/u.test(before) &&
        /^[^;]*,/u.test(tail) &&
        /;\s*(?:and|or)\b[^;]*$/iu.test(tail)
      ) &&
      (conjunctiveAdverbPattern.test(tail) || clauseStartPattern.test(tail))
    ) {
      return {
        column: index + 1,
        length: match.groups?.semicolon.length ?? 0
      };
    }
  }
  return undefined;
};

/**
 * Markdownlint rule requiring one prose sentence per source line.
 */
export const sentencePerLine: Rule = {
  description: "Prose sentences must be separated by physical source lines",
  function: (params, onError) => {
    if (!protectedDocument(params)) {
      const reported = new Set<string>();
      for (const paragraph of proseBlocks(
        params.parsers.micromark?.tokens ?? []
      )) {
        const sourceLines = [...segmentsByLine(paragraph)];
        const protectedLines = protectText(
          sourceLines.map(([, segments]) => rebuildLine(segments)).join("\n")
        ).split("\n");
        for (const [index, [lineNumber]] of sourceLines.entries()) {
          const line = protectedLines[index] ?? "";
          const continuationFinding =
            sourceLines[index - 1]?.[0] === lineNumber - 1
              ? continuation(protectedLines[index - 1], line)
              : undefined;
          if (continuationFinding) {
            onError({
              context: (params.lines[lineNumber - 1] ?? "").trim(),
              detail: /^[a-z]/u.test(line.trimStart())
                ? "Sentence continues from the previous source line; keep the sentence on one line."
                : "End the previous instruction with a sentence terminator before this continuation.",
              lineNumber,
              range: [continuationFinding.column, continuationFinding.length]
            });
          }
          for (const [kind, finding] of [
            ["sentences", joinedSentence(line)],
            ["semicolon", joinedSemicolon(line)]
          ] as const) {
            if (finding) {
              const key = `${lineNumber}:${kind}`;
              if (!reported.has(key)) {
                reported.add(key);
                onError({
                  context: (params.lines[lineNumber - 1] ?? "").trim(),
                  detail:
                    kind === "sentences"
                      ? "Multiple sentences on one line; put each sentence on its own line."
                      : "Semicolon-joined sentences on one line; put each sentence on its own line.",
                  lineNumber,
                  range: [finding.column, finding.length]
                });
              }
            }
          }
        }
      }
    }
  },
  names: ["docs/sentence-per-line"],
  parser: "micromark",
  tags: ["docs", "sentences"]
};

const selectedDocument = (params: RuleParams): boolean => {
  const config: unknown = params.config;
  const paths: unknown =
    typeof config === "object" && config !== null && "paths" in config
      ? config.paths
      : undefined;
  const name = params.name.replaceAll("\\", "/");
  return (
    !Array.isArray(paths) ||
    paths.some(
      (prefix: unknown) =>
        typeof prefix === "string" &&
        (name.startsWith(prefix) || name.includes(`/${prefix}`))
    )
  );
};

/**
 * Report authored prose punctuation without rewriting source or quotations.
 */
export const noEmDash: Rule = {
  description: "Avoid em dashes in authored prose",
  function: (params, onError) => {
    if (!protectedDocument(params) && selectedDocument(params)) {
      for (const paragraph of proseBlocks(
        params.parsers.micromark?.tokens ?? []
      )) {
        const sourceLines = [...segmentsByLine(paragraph)];
        const protectedLines = protectText(
          sourceLines.map(([, segments]) => rebuildLine(segments)).join("\n")
        ).split("\n");
        for (const [index, [lineNumber]] of sourceLines.entries()) {
          for (const match of (protectedLines[index] ?? "").matchAll(
            /\u2014/gu
          )) {
            onError({ lineNumber, range: [(match.index ?? 0) + 1, 1] });
          }
        }
      }
    }
  },
  names: ["docs/no-em-dash"],
  parser: "micromark",
  tags: ["docs", "prose"]
};

/**
 * Diagnose relative skill-file destinations without resolving or rewriting links.
 */
export const noRelativeSkillLinks: Rule = {
  description: "Use skill names instead of relative skill-file links",
  function: (params, onError) => {
    if (!protectedDocument(params) && selectedDocument(params)) {
      const visit = (
        token: MicromarkToken,
        quoted = new Map<number, string>()
      ): void => {
        let protectedLines = quoted;
        if (token.type === "paragraph") {
          protectedLines = new Map(
            protectText(token.text)
              .split(/\r\n|\r|\n/u)
              .map((line, index) => [
                token.startLine + index,
                `${" ".repeat(index === 0 ? token.startColumn - 1 : 0)}${line}`
              ])
          );
        }
        if (
          token.type === "resourceDestination" ||
          token.type === "definitionDestination"
        ) {
          const destination = token.text.replaceAll(/^<|>$/gu, "");
          const visible = protectedLines
            .get(token.startLine)
            ?.slice(token.startColumn - 1, token.endColumn - 1);
          if (
            (visible === undefined || visible.trim() !== "") &&
            !/^(?:[a-z][a-z\d+.-]*:|\/|#)/iu.test(destination) &&
            /(?:^|\/)SKILL\.md(?:[?#].*)?$/u.test(destination)
          ) {
            onError({
              lineNumber: token.startLine,
              range: [
                token.startColumn,
                Math.max(1, token.endColumn - token.startColumn)
              ]
            });
          }
        } else if (
          !skippedContainerTypes.has(token.type) &&
          token.type !== "codeText" &&
          (token.type !== "blockQuote" || alertPattern.test(token.text))
        ) {
          for (const child of token.children) {
            visit(child, protectedLines);
          }
        }
      };
      for (const token of params.parsers.micromark?.tokens ?? []) {
        visit(token);
      }
    }
  },
  names: ["docs/no-relative-skill-links"],
  parser: "micromark",
  tags: ["docs", "links"]
};

/**
 * Share the Micromark-aware diagnostic rules through one parser integration.
 */
export default [sentencePerLine, noEmDash, noRelativeSkillLinks];
